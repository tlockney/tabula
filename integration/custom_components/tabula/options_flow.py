"""The hub's options flow: the settings editor until the panel exists (plan 5.6).

Settings are data, not entities: they live in the SettingsStore, and this flow
is only the editor. Step one picks a paired tablet; step two is a flat form
generated by walking schema/settings.schema.json - every leaf whose role tag
is editable (identity, connection, shared; never hardware facts, F-MGT-03)
becomes one field, with the schema's enum, bounds and default. List-valued
leaves (settings v2: the At a Glance entities, the widget's visible values,
the schedule's slots) become one multi-line text field each - one item per
line for scalar arrays, YAML for the slots - parsed and validated against the
schema on submit. No hand-kept field list exists: adding a property to the
schema is enough to show it.

Submitting saves the next revision and pushes it to the device when it is
connected (schedule_settings_push); a device that is not, or that refuses,
converges at its next registration (PROTOCOL.md 4.2, 4.5). The flow does not
touch the entry's options - the entry keeps what it had.
"""

from __future__ import annotations

import copy
from typing import Any

import voluptuous as vol
import yaml
from homeassistant.config_entries import ConfigFlowResult, OptionsFlow
from homeassistant.const import CONF_DEVICE_ID
from homeassistant.helpers import selector

from . import TabulaHub
from .const import DOMAIN, INTERCOM_PERSONS
from .intents import PersonMapError, parse_persons, persons_to_text
from .settings import (
    NO_DEFAULT,
    SettingsError,
    SettingsField,
    SettingsSchema,
    delete_path,
    get_path,
    schedule_settings_push,
    set_path,
)


def _validator(field: SettingsField) -> Any:
    """A voluptuous validator for one leaf: enum, bounds, or plain type.

    The JSON schema re-validates the assembled document on submit, so the
    vol validators only carry what the frontend can enforce while typing.
    Strings accept empty: for leaves with no default (identity, connection)
    a blank means unset, and the submit-time assembly maps it back (a too
    short real value still fails the JSON schema and reshow the form).

    List-valued leaves (settings v2) get a multi-line text editor: the value
    is parsed and schema-checked on submit (array_from_text), which is the
    "usable, not polished" editor the packet calls for - the Tabularium
    (Phase 5) is the real settings UI.
    """
    if field.type == "array":
        return selector.TextSelector({"multiline": True})
    if field.enum is not None:
        return vol.In(list(field.enum))
    if field.type == "integer":
        return vol.All(
            vol.Coerce(int),
            vol.Range(min=field.minimum, max=field.maximum),
        )
    if field.type == "boolean":
        return bool
    return vol.All(str, vol.Length(min=0, max=field.max_length))


def array_to_text(field: SettingsField, value: Any) -> str:
    """An array value as the editor's text: one item per line for arrays of
    scalars, YAML for arrays of objects (the schedule's slots)."""
    if value is None:
        return ""
    if field.array_items == "object":
        return yaml.safe_dump(list(value), sort_keys=False) if value else ""
    return "\n".join(str(item) for item in value)


def array_from_text(field: SettingsField, value: Any) -> list[Any]:
    """The submitted editor value parsed back into the array.

    A value that is already a list (entity writes, tests) passes through.
    Blank text is the empty array. For arrays of objects the text must be a
    YAML (or JSON) list of objects; anything else raises SettingsError
    naming the field, which the flow reshows as that field's error.
    """
    if isinstance(value, list):
        return value
    text = value.strip() if isinstance(value, str) else ""
    if not text:
        return []
    if field.array_items == "object":
        try:
            parsed = yaml.safe_load(text)
        except yaml.YAMLError as e:
            raise SettingsError([f"{'/'.join(field.path)}: not valid YAML or JSON ({e})"]) from e
        if not isinstance(parsed, list) or not all(isinstance(item, dict) for item in parsed):
            raise SettingsError(
                [f"{'/'.join(field.path)}: must be a list of objects, one per line"]
            )
        return parsed
    return [line.strip() for line in text.splitlines() if line.strip()]


def settings_form(schema: SettingsSchema, current: dict[str, Any] | None) -> vol.Schema:
    """The per-device form: one flat field per editable leaf, in schema order.

    Stored values are suggested; absent ones fall back to the schema default,
    or to an empty string for leaves with no default (identity, connection),
    which submit-time assembly maps back to "unset". Array leaves show their
    value as the editor text (array_to_text).
    """
    fields: dict[Any, Any] = {}
    for field in schema.editable_fields():
        stored = get_path(current, field.path)
        validator = _validator(field)
        if field.type == "array":
            shown = field.default if stored is NO_DEFAULT else stored
            fields[vol.Optional(field.key, default=array_to_text(field, shown))] = validator
        elif field.default is NO_DEFAULT:
            shown = "" if stored is NO_DEFAULT else stored
            fields[vol.Optional(field.key, description={"suggested_value": shown})] = validator
        else:
            shown = field.default if stored is NO_DEFAULT else stored
            fields[vol.Optional(field.key, default=shown)] = validator
    return vol.Schema(fields)


def assemble_document(
    schema: SettingsSchema, user_input: dict[str, Any], base: dict[str, Any] | None
) -> dict[str, Any]:
    """The submitted form values merged onto the stored document (or defaults).

    An editable leaf left blank that has no schema default goes back to unset
    (delete_path); everything else keeps its stored or default value. Array
    leaves parse their editor text (array_from_text); parse problems raise
    SettingsError and the flow reshows the form on the offending field.
    """
    document = copy.deepcopy(base) if base is not None else schema.defaults()
    for field in schema.editable_fields():
        if field.key not in user_input:
            continue
        value = user_input[field.key]
        if field.type == "array":
            set_path(document, field.path, array_from_text(field, value))
        elif field.default is NO_DEFAULT and value in (None, ""):
            delete_path(document, field.path)
        else:
            set_path(document, field.path, value)
    return document


def cross_field_problems(document: dict[str, Any]) -> list[str]:
    """Rules that span two leaves, which no single-subschema check can make.

    P9.5: ``intercom.auto_answer: listed`` with no ``auto_answer_from`` reads
    as "answer only these callers" while naming none, and the device would ring
    instead. The save is refused so the two leaves cannot disagree; the device
    still treats the pair as a plain ring if a document reaches it another way.
    """
    intercom = document.get("intercom")
    if not isinstance(intercom, dict):
        return []
    listed = intercom.get("auto_answer") == "listed"
    if listed and not intercom.get("auto_answer_from"):
        return [
            "intercom/auto_answer_from: 'listed' needs at least one caller "
            "(or choose 'off' or 'all')"
        ]
    return []


def _form_errors(problems: list[str], schema: SettingsSchema) -> dict[str, str]:
    """Map schema problems onto form fields: the failing path becomes the key.

    An error inside a list (``schedule/slots/0/start``) has no field of its
    own; it maps onto the list's field (``schedule_slots``), never onto a
    scalar field whose key merely starts the same way.
    """
    errors: dict[str, str] = {}
    editable = {f.key for f in schema.editable_fields()}
    arrays = {f.key for f in schema.editable_fields() if f.type == "array"}
    for problem in problems:
        path = problem.partition(": ")[0]
        key = path.replace("/", "_")
        if key in editable:
            errors[key] = "invalid_settings"
            continue
        inside = next((k for k in arrays if key.startswith(k + "_")), None)
        errors[inside or "base"] = "invalid_settings"
    return errors or {"base": "invalid_settings"}


class TabulaOptionsFlow(OptionsFlow):
    """A menu: per-tablet settings, or the intercom names (P9.6)."""

    def __init__(self) -> None:
        self._device_id: str | None = None

    async def async_step_init(self, user_input: dict[str, Any] | None = None) -> ConfigFlowResult:
        """Choose what to edit: a tablet's settings, or the spoken names."""
        if TabulaHub.get(self.hass) is None:
            return self.async_abort(reason="hub_not_loaded")
        return self.async_show_menu(step_id="init", menu_options=["settings", "persons"])

    async def async_step_settings(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Pick which paired tablet to edit."""
        hub = TabulaHub.get(self.hass)
        if hub is None:
            return self.async_abort(reason="hub_not_loaded")
        if user_input is not None:
            record = next(
                (r for r in hub.devices.values() if r.ha_device_id == user_input[CONF_DEVICE_ID]),
                None,
            )
            if record is None:
                return self.async_abort(reason="unknown_device")
            self._device_id = record.device_id
            return await self.async_step_device()
        if not hub.devices:
            return self.async_abort(reason="no_devices")
        return self.async_show_form(
            step_id="settings",
            data_schema=vol.Schema(
                {
                    vol.Required(CONF_DEVICE_ID): selector.DeviceSelector(
                        {"filter": {"integration": DOMAIN}}
                    ),
                }
            ),
        )

    async def async_step_persons(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """The names an intercom request may speak: a person, an area or a tablet.

        A name the household chooses, not one HA already knows: a person is not
        an area and not a tablet, so an unrecognised "call Thomas" is answered
        rather than guessed (ADR 0036). The editor is YAML, one entry per
        person, and the whole map is replaced on submit; the intents read it
        from the entry's options at the moment they run, so the next request
        uses it without a reload.
        """
        if TabulaHub.get(self.hass) is None:
            return self.async_abort(reason="hub_not_loaded")
        stored = self.config_entry.options.get(INTERCOM_PERSONS) or []
        current = persons_to_text(stored) if isinstance(stored, list) else ""
        if user_input is None:
            return self.async_show_form(
                step_id="persons",
                data_schema=vol.Schema(
                    {
                        vol.Optional("persons", default=current): selector.TextSelector(
                            {"multiline": True}
                        )
                    }
                ),
                description_placeholders={"problems": ""},
            )
        try:
            persons = parse_persons(user_input.get("persons", ""))
        except PersonMapError as err:
            return self.async_show_form(
                step_id="persons",
                data_schema=vol.Schema(
                    {
                        vol.Optional(
                            "persons", default=str(user_input.get("persons", ""))
                        ): selector.TextSelector({"multiline": True})
                    }
                ),
                errors={"persons": "invalid_persons"},
                # Every problem is listed under the editor, not just the first
                # (ADR 0036 decision 6): a refused save says what to fix.
                description_placeholders={
                    "problems": "\n\n" + "\n".join(f"- {p}" for p in err.problems)
                },
            )
        return self.async_create_entry(
            title="", data={**self.config_entry.options, INTERCOM_PERSONS: persons}
        )

    async def async_step_device(self, user_input: dict[str, Any] | None = None) -> ConfigFlowResult:
        """Edit one device's settings; save and push on submit."""
        hub = TabulaHub.get(self.hass)
        device_id = self._device_id
        if hub is None:
            return self.async_abort(reason="hub_not_loaded")
        if device_id is None:
            return self.async_abort(reason="unknown_device")
        record = hub.devices.get(device_id)
        if record is None:
            return self.async_abort(reason="unknown_device")
        stored = hub.settings.get(record.device_id)
        placeholders = {"name": record.name or record.model or record.device_id[:8]}
        if user_input is None:
            return self.async_show_form(
                step_id="device",
                data_schema=settings_form(hub.settings.schema, stored.settings if stored else None),
                description_placeholders=placeholders,
            )
        document: dict[str, Any] | None = None
        # What the save replaces, for the profile override rule (ADR 0035 item 1).
        before = copy.deepcopy(stored.settings) if stored is not None else None
        try:
            document = assemble_document(
                hub.settings.schema, user_input, stored.settings if stored else None
            )
            hub.settings.schema.validate(document)
            # Rules that span leaves come after the per-leaf validation, so a
            # genuinely invalid value is reported as itself (P9.5)
            cross_field = cross_field_problems(document)
            if cross_field:
                raise SettingsError(cross_field)
        except SettingsError as e:
            base = document if document is not None else (stored.settings if stored else None)
            return self.async_show_form(
                step_id="device",
                data_schema=settings_form(hub.settings.schema, base),
                description_placeholders=placeholders,
                errors=_form_errors(e.problems, hub.settings.schema),
            )
        await hub.settings.async_save(record.device_id, document)
        # A per-device edit of a key the device's profile covers is that key's
        # override (ADR 0035 item 1): the form writes a whole document, so the
        # changed covered keys come from what the save replaced.
        await hub.profiles.async_record_document_overrides(record.device_id, before, document)
        hub.apply_identity(record)
        schedule_settings_push(hub, record)
        # The entry's options are not this flow's storage (settings live in the
        # SettingsStore); write the current options back unchanged.
        return self.async_create_entry(title="", data={**self.config_entry.options})
