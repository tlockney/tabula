#!/usr/bin/env bash
# P3.3 hardware check (docs/packets/P3.3-clock-faces.md):
#   with the clock settings configured in HA, the tablet shows (a) the
#   digital face with a changed font, seconds and date line, (b) the analog
#   face with hands, and (c) the digital face over a URL background image
#   with the darkening layer visible; a broken URL keeps the previous
#   image, and a settings write with the same URL reloads it (F-SSV-08,
#   F-SSV-09; logcat lines from TabulaClock are the load evidence).
#
# Prerequisites: the tablet runs a P3.3 build, is provisioned
# (tools/device/provision.sh) and paired, the app is in the foreground with
# the panel on, and the clock settings are configured in HA (the entry's
# Configure page; the settings apply while the clock shows, F-SSV-09):
#   screensaver mode: clock
#   clock face: digital, font family: serif, font weight: 700,
#   seconds: on, date line: on, background source: empty
# The environment has:
#   TABULA_HA_URL            e.g. http://homeassistant.local:8123
#   TABULA_HA_TOKEN          a long-lived access token (any user that may call services)
#   TABULA_SCREENSAVER       the tablet's screensaver switch, e.g. switch.office_kiosk_screensaver
#   TABULA_BACKGROUND        the tablet's clock background text entity, e.g. text.office_kiosk_clock_background
#   TABULA_PHOTOS           a directory of test JPEGs; default: generated by
#                            tools/device/gen_test_photos.py into build/test-photos
#   TABULA_HOST_IP           the address the tablet reaches this Mac on; default: en0's address
#   TABULA_HTTP_PORT        the port to serve the background on (default 18923)
#   ANDROID_SERIAL          optional, picks the tablet when several are attached
#
# Steps 3 and 5 ask the verifier to switch the face in HA's Configure page;
# the save is the settings write (F-HA-11), so the face changes while the
# screensaver stays up. The script serves the background itself over plain
# HTTP from the test-photos directory: the same URL is re-served with
# different bytes to show that writing the same source still reloads it
# (F-SSV-09).
#
# The script cleans up after itself: a trap turns the screensaver switch off,
# clears the background source and stops the HTTP server on any failure,
# Ctrl-C and normal exit. It never touches the tablet's Wi-Fi, pairing or
# app settings. Paste the whole output into the packet Result section.

set -euo pipefail

serial="${ANDROID_SERIAL:-}"
adb() {
    if [[ -n "$serial" ]]; then command adb -s "$serial" "$@"; else command adb "$@"; fi
}
pkg=net.lockney.tabula
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
photos_dir="${TABULA_PHOTOS:-$repo/build/test-photos}"
host_ip="${TABULA_HOST_IP:-$(ipconfig getifaddr en0 || true)}"
port="${TABULA_HTTP_PORT:-18923}"

: "${TABULA_HA_URL:?set TABULA_HA_URL, e.g. http://homeassistant.local:8123}"
: "${TABULA_HA_TOKEN:?set TABULA_HA_TOKEN to a long-lived access token}"
: "${TABULA_SCREENSAVER:?set TABULA_SCREENSAVER to the tablet screensaver switch entity id}"
: "${TABULA_BACKGROUND:?set TABULA_BACKGROUND to the tablet clock background text entity id}"
: "${host_ip:?set TABULA_HOST_IP to the address the tablet reaches this Mac on (en0 has none)}"
if [[ ! -d "$photos_dir" ]]; then
    echo "no test photos in $photos_dir; generate them first:" >&2
    echo "  uv run --with 'pillow>=10' --with piexif python tools/device/gen_test_photos.py" >&2
    exit 1
fi
# child processes read the token
export TABULA_HA_TOKEN

step() { echo; echo "== $*"; }
fail() { echo "FAIL: $*" >&2; exit 1; }

ha_call() { # ha_call <domain> <service> <json body>
    curl -fsS -X POST \
        -H "Authorization: Bearer $TABULA_HA_TOKEN" -H "Content-Type: application/json" \
        -d "$3" "${TABULA_HA_URL%/}/api/services/$1/$2" > /dev/null
    echo "-- called $1.$2 $3"
}
ha_state() { # ha_state <entity_id> -> prints the state
    curl -fsS -H "Authorization: Bearer $TABULA_HA_TOKEN" "${TABULA_HA_URL%/}/api/states/$1" \
        | python3 -c 'import json,sys; print(json.load(sys.stdin)["state"])'
}
ha_state_is() { [[ "$(ha_state "$1")" == "$2" ]]; }
wait_for() { # wait_for <description> <timeout s> <command...>
    local what="$1" timeout="$2"; shift 2
    local waited=0
    until "$@"; do
        (( waited >= timeout )) && fail "timed out after ${waited}s waiting for $what"
        sleep 1; waited=$((waited + 1))
    done
    echo "-- $what after ${waited}s"
}
ask() { # ask <question> -> fails unless the verifier answers y
    local answer
    read -r -p "$1 [y/n] " answer
    [[ "$answer" == y* ]] || fail "verifier answered '$answer' to: $1"
    echo "-- verifier: yes ($1)"
}
set_background() { # set_background <value>
    ha_call text set_value "{\"entity_id\": \"$TABULA_BACKGROUND\", \"value\": \"$1\"}"
}
load_count() { # logcat background load lines so far
    adb logcat -d -s TabulaClock:I 2>/dev/null | grep -c "background: load " || true
}
shown_count() { # logcat background show lines so far
    adb logcat -d -s TabulaClock:I 2>/dev/null | grep -c "background: shown" || true
}
fail_count() { # logcat background failure lines so far
    adb logcat -d -s TabulaClock:W 2>/dev/null | grep -c "background: load failed" || true
}

bg_url="http://$host_ip:$port/clock-bg.jpg"
serve_dir="$(mktemp -d)"
cp "$photos_dir"/p38-1.jpg "$serve_dir/clock-bg.jpg"
[[ -f "$serve_dir/clock-bg.jpg" ]] || fail "no p38-1.jpg in $photos_dir; generate the test photos first"
python3 -m http.server "$port" --bind 0.0.0.0 --directory "$serve_dir" > /dev/null 2>&1 &
server=$!
cleanup() {
    ha_state_is "$TABULA_SCREENSAVER" on && ha_call switch turn_off "{\"entity_id\": \"$TABULA_SCREENSAVER\"}" || true
    # a blank source clears the background (F-SSV-09)
    set_background "" || true
    kill "$server" 2>/dev/null || true
    rm -rf "$serve_dir"
}
trap cleanup EXIT

step "1. app running, screensaver off, HTTP server up"
adb devices -l
adb shell pidof "$pkg" || fail "Tabula is not running"
sleep 2
kill -0 "$server" 2>/dev/null || fail "the HTTP server did not start on port $port"
curl -fsS "http://127.0.0.1:$port/clock-bg.jpg" -o /dev/null || fail "the background URL does not serve locally"
adb shell input keyevent KEYCODE_SHIFT_LEFT
sleep 2
ha_state_is "$TABULA_SCREENSAVER" off || fail "the screensaver is already on"

step "2. the digital face with the changed font, seconds and date line"
adb logcat -c
ha_call tabula screensaver "{\"entity_id\": \"$TABULA_SCREENSAVER\", \"active\": true, \"mode\": \"clock\"}"
wait_for "the screensaver switch to turn on" 10 ha_state_is "$TABULA_SCREENSAVER" on
ask "Does the tablet show the digital clock in a serif, bold face (not the light default)?"
ask "Does the time tick every second, with the AM/PM marker and the date line under it?"

step "3. the analog face with hands (a settings write while the clock shows)"
echo "-- in HA, set the clock face to 'analog' on the device's Configure page and save."
ask "Have you saved face = analog in HA?"
sleep 2
ha_state_is "$TABULA_SCREENSAVER" on || fail "the settings write dismissed the screensaver (it must not)"
ask "Does the tablet show an analog dial with hour, minute and second hands?"
ask "Are the date line and the AM/PM marker under the dial?"

step "4. back to digital, over a URL background image with the darkening layer"
echo "-- in HA, set the clock face back to 'digital' on the device's Configure page and save."
ask "Have you saved face = digital in HA?"
sleep 2
loads_before="$(load_count)"
set_background "$bg_url"
wait_for "the background load to reach the device" 15 bash -c "(( \$(load_count) > $loads_before ))"
shown_before="$(shown_count)"
sleep 3
ask "Does the tablet show the digital clock over the photo, darkened (the darkening layer, F-SSV-09)?"
ask "Is the clock still readable across the room?"

step "5. a broken URL keeps the previous image"
fails_before="$(fail_count)"
set_background "http://$host_ip:$port/missing.jpg"
wait_for "the failed load to reach the device" 15 bash -c "(( \$(fail_count) > $fails_before ))"
sleep 3
ask "Does the tablet still show the previous photo behind the clock (nothing cleared)?"

step "6. a settings write with the same URL reloads it (F-SSV-09)"
cp "$photos_dir"/p38-2.jpg "$serve_dir/clock-bg.jpg"
[[ -f "$serve_dir/clock-bg.jpg" ]] || fail "no p38-2.jpg in $photos_dir"
loads_before="$(load_count)"
set_background "$bg_url"  # the same URL, the same value: still a fresh load
wait_for "the same-URL reload to reach the device" 15 bash -c "(( \$(load_count) > $loads_before ))"
sleep 3
ask "Has the photo behind the clock changed to the other test photo (the same URL, reloaded)?"
ha_state_is "$TABULA_SCREENSAVER" on || fail "the reload dismissed the screensaver (it must not)"

step "7. a centre tap dismisses"
size="$(adb shell wm size | sed -n 's/.*: \([0-9]*\)x\([0-9]*\).*/\1 \2/p' | tail -1)"
read -r w h <<< "$size"
adb shell input tap $((w / 2)) $((h / 2))
wait_for "the screensaver switch to turn off (centre tap dismisses)" 10 ha_state_is "$TABULA_SCREENSAVER" off
ask "Is the dashboard back, with no image left on screen?"

echo
echo "== PASS: P3.3 hardware check complete"
