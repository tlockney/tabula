#!/usr/bin/env bash
# P3.8 hardware check (docs/packets/P3.8-gallery-core.md):
#   with a folder of test photos on the tablet, the slideshow runs at the
#   configured interval with crossfade; edge taps step slides and restart the
#   interval; a center tap dismisses; the EXIF overlay shows date/camera; and
#   the app's memory after a run of slides stays within the script's bound
#   (F-SSV-12, F-SSV-04; dumpsys meminfo, packet P3.8).
#
# Prerequisites: the tablet runs a P3.8 build, is provisioned
# (tools/device/provision.sh) and paired, the app is in the foreground with
# the panel on, and the photos settings are configured in HA (the entry's
# Configure page; the settings apply when the screensaver starts, ADR 0016):
#   screensaver mode: photos
#   photos source: folder, folder path: /storage/emulated/0/Android/data/net.lockney.tabula/files/photos
#   slide interval: 5 s, transition: crossfade, fit: smart fill,
#   edge taps: on, EXIF details: on
# The environment has:
#   TABULA_HA_URL            e.g. http://homeassistant.local:8123
#   TABULA_HA_TOKEN          a long-lived access token (any user that may call services)
#   TABULA_SCREENSAVER       the tablet's screensaver switch, e.g. switch.office_kiosk_screensaver
#   TABULA_PHOTOS            a directory of test JPEGs; default: generated by
#                            tools/device/gen_test_photos.py into build/test-photos
#   TABULA_SLIDE_INTERVAL_S  the configured slide interval, seconds (default 5)
#   TABULA_MEM_BOUND_MB      the memory bound, MiB (default 48; reasoning in
#                            docs/decisions/0016 and the packet Result)
#   ANDROID_SERIAL          optional, picks the tablet when several are attached
#
# The test photos get onto the device by ADB push into the app's external
# files directory (the configured folder path): the shell can write it on the
# HD 10 Plus, and the app can read its own directory without any storage
# permission (ADR 0016). The picker route (the notification's "Pick photos"
# action, SAF) is documented in DEVICE.md and can be checked by hand.
#
# The script cleans up after itself: a trap turns the screensaver switch off
# and puts the tablet's Wi-Fi and settings back on any failure, Ctrl-C and
# normal exit. The pushed photos are left in place (harmless app storage);
# delete them with adb shell rm if a clean slate is wanted. Paste the whole
# output into the packet Result section.

set -euo pipefail

serial="${ANDROID_SERIAL:-}"
adb() {
    if [[ -n "$serial" ]]; then command adb -s "$serial" "$@"; else command adb "$@"; fi
}
pkg=net.lockney.tabula
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
photos_dir="${TABULA_PHOTOS:-$repo/build/test-photos}"
interval_s="${TABULA_SLIDE_INTERVAL_S:-5}"
mem_bound_mb="${TABULA_MEM_BOUND_MB:-48}"
device_photos="/storage/emulated/0/Android/data/$pkg/files/photos"

: "${TABULA_HA_URL:?set TABULA_HA_URL, e.g. http://homeassistant.local:8123}"
: "${TABULA_HA_TOKEN:?set TABULA_HA_TOKEN to a long-lived access token}"
: "${TABULA_SCREENSAVER:?set TABULA_SCREENSAVER to the tablet screensaver switch entity id}"
if [[ ! -d "$photos_dir" ]]; then
    echo "no test photos in $photos_dir; generate them first:" >&2
    echo "  uv run --with 'pillow>=10' --with piexif python tools/device/gen_test_photos.py" >&2
    exit 1
fi
# child processes (ha_events.py) read the token
export TABULA_HA_TOKEN

step() { echo; echo "== $*"; }
fail() { echo "FAIL: $*" >&2; exit 1; }

ha_call() { # ha_call <domain> <service> <json body>
    curl -fsS -X POST \
        -H "Authorization: Bearer $TABULA_HA_TOKEN" -H "Content-Type: application/json" \
        -d "$3" "${TABULA_HA_URL%/}/api/services/$1/$2" > /dev/null
    echo "-- called $1.$2 $3"
}
ha_state() { # ha_state <entity_id> -> prints the state
    curl -fsS -H "Authorization: Bearer $TABULA_HA_TOKEN" "${TABULA_HA_URL%/}/api/states/$1" \
        | python3 -c 'import json,sys; print(json.load(sys.stdin)["state"])'
}
ha_state_is() { [[ "$(ha_state "$1")" == "$2" ]]; }
wait_for() { # wait_for <description> <timeout s> <command...>
    local what="$1" timeout="$2"; shift 2
    local waited=0
    until "$@"; do
        (( waited >= timeout )) && fail "timed out after ${timeout}s waiting for $what"
        sleep 1; waited=$((waited + 1))
    done
    echo "-- $what after ${waited}s"
}
wait_for_slides() { # wait_for_slides <count> <timeout s>
    local want="$1" timeout="$2" waited=0
    until (( $(slide_count) >= want )); do
        (( waited >= timeout )) && fail "timed out after ${timeout}s waiting for $want slides"
        sleep 1; waited=$((waited + 1))
    done
    echo "-- $want slides after ${waited}s"
}
ask() { # ask <question> -> fails unless the verifier answers y
    local answer
    read -r -p "$1 [y/n] " answer
    [[ "$answer" == y* ]] || fail "verifier answered '$answer' to: $1"
    echo "-- verifier: yes ($1)"
}
slide_count() { # logcat lines the gallery logged so far
    adb logcat -d -s TabulaGallery:I 2>/dev/null | grep -c "slide: " || true
}
total_pss_kb() { # the app's TOTAL PSS from dumpsys meminfo
    adb shell dumpsys meminfo "$pkg" | awk '/TOTAL PSS:/ {print $3; exit}'
}

events_log="$(mktemp)"
UV_CONFIG_FILE="$here/../uv.toml" \
    uv run --directory "$repo" python tools/device/ha_events.py \
    --ha "$TABULA_HA_URL" --token "$TABULA_HA_TOKEN" --event tabula_screensaver --seconds 1200 \
    > "$events_log" &
listener=$!
cleanup() {
    ha_state_is "$TABULA_SCREENSAVER" on && ha_call switch turn_off "{\"entity_id\": \"$TABULA_SCREENSAVER\"}" || true
    kill "$listener" 2>/dev/null || true
}
trap cleanup EXIT

step "1. app running, screensaver off, photos pushed"
adb devices -l
adb shell pidof "$pkg" || fail "Tabula is not running"
sleep 3
kill -0 "$listener" 2>/dev/null || fail "the HA event listener did not start"
adb shell input keyevent KEYCODE_SHIFT_LEFT
sleep 2
ha_state_is "$TABULA_SCREENSAVER" off || fail "the screensaver is already on"

adb shell mkdir -p "$device_photos"
pushed=0
for photo in "$photos_dir"/*.jpg; do
    adb push "$photo" "$device_photos/" > /dev/null
    pushed=$((pushed + 1))
done
echo "-- pushed $pushed photos into $device_photos"
(( pushed >= 3 )) || fail "need at least 3 test photos, found $pushed in $photos_dir"
on_device="$(adb shell ls "$device_photos" | grep -c '\.jpg' || true)"
echo "-- photos on device: $on_device"
(( on_device >= pushed )) || fail "only $on_device of $pushed photos readable on device"

step "2. start the slideshow from HA and show the first slide"
pss_before="$(total_pss_kb)"
echo "-- TOTAL PSS before: ${pss_before} kB"
adb logcat -c
ha_call tabula screensaver "{\"entity_id\": \"$TABULA_SCREENSAVER\", \"active\": true, \"mode\": \"photos\"}"
wait_for "the screensaver switch to turn on" 10 ha_state_is "$TABULA_SCREENSAVER" on
wait_for_slides 1 15
ask "Does the tablet show a photo full screen?"
ask "Does the details overlay show a date and a camera (on the EXIF photos; not on p38-4)?"

step "3. the slideshow advances at the interval with crossfade"
sleep_for=$((interval_s * 3))
echo "-- waiting ${sleep_for}s for three more slides…"
sleep "$sleep_for"
slides="$(slide_count)"
echo "-- slides rendered in $((sleep_for))s: $slides (expect about 4: one at start plus one per ${interval_s}s interval)"
(( slides >= 4 )) || fail "expected at least 4 slides, logcat shows $slides"
ask "Did the photo crossfade to a new one roughly every ${interval_s}s?"
ask "Do photos whose shape differs from the panel (p38-2, p38-3) show the whole photo over blurred, darkened bars (smart fill)?"

step "4. edge taps step slides and restart the interval; the centre dismisses"
size="$(adb shell wm size | sed -n 's/.*: \([0-9]*\)x\([0-9]*\).*/\1 \2/p' | tail -1)"
read -r w h <<< "$size"
edge_x=$((w * 4 / 100))    # inside the left zone (8% wide, ADR 0002)
right_x=$((w * 96 / 100))  # inside the right zone
mid_y=$((h / 2))
before="$(slide_count)"
adb shell input tap "$right_x" "$mid_y"
sleep 2
after="$(slide_count)"
echo "-- right-edge tap: slides $before -> $after (a step forward)"
(( after > before )) || fail "a right-edge tap did not step a slide"
ha_state_is "$TABULA_SCREENSAVER" on || fail "an edge tap dismissed the screensaver (it must not, F-SSV-04)"

before="$after"
adb shell input tap "$edge_x" "$mid_y"
sleep 2
after="$(slide_count)"
echo "-- left-edge tap: slides $before -> $after (a step back)"
(( after > before )) || fail "a left-edge tap did not step a slide"
ha_state_is "$TABULA_SCREENSAVER" on || fail "an edge tap dismissed the screensaver (it must not, F-SSV-04)"

adb shell input tap $((w / 2)) $((h / 2))
wait_for "the screensaver switch to turn off (centre tap dismisses)" 10 ha_state_is "$TABULA_SCREENSAVER" off
ask "Is the dashboard back?"

step "5. memory across the run (dumpsys meminfo)"
pss_after="$(total_pss_kb)"
echo "-- TOTAL PSS after: ${pss_after} kB"
delta_mb=$(( (pss_after - pss_before) / 1024 ))
echo "-- growth: ${delta_mb} MB (bound: ${mem_bound_mb} MB)"
(( delta_mb <= mem_bound_mb )) || fail "memory grew by ${delta_mb} MB, over the ${mem_bound_mb} MB bound"

step "6. tabula_screensaver events received by HA"
sleep 2
cat "$events_log"
count="$(grep -c '"data"' "$events_log" || true)"
(( count >= 2 )) || fail "expected at least 2 tabula_screensaver events (1 start, 1 stop), got $count"
echo "-- $count events"

echo
echo "P3.8 hardware check complete; paste everything above into the packet Result."
